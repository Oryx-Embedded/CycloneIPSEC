/**
 * @brief Process EAP MS-CHAP-V2 request
 * @param[in] sa Pointer to the IKE SA
 * @param[in] request Pointer to the EAP MS-CHAP-V2 request
 * @param[in] length Length of the EAP MS-CHAP-V2 request, in bytes
 * @return Error code
 **/

error_t ikeProcessEapMschapv2Request(IkeSaEntry *sa,
   const IkeEapMschapv2Packet *request, size_t length)
{
   error_t error;

   //Malformed MS-CHAP-V2 packet?
   if(length < sizeof(IkeEapMschapv2Packet))
      return ERROR_INVALID_LENGTH;

   //The OpCode field identifies the type of MS-CHAP-V2 packet
   if(request->opcode == IKE_EAP_MSCHAPV2_CODE_CHALLENGE)
   {
      //Process EAP MS-CHAP-V2 Challenge packet
      error = ikeProcessEapMschapv2Challenge(sa,
         (IkeEapMschapv2Challenge *) request, length);
   }
   else if(request->opcode == IKE_EAP_MSCHAPV2_CODE_SUCCESS)
   {
      //Process EAP MS-CHAP-V2 Success Request packet
      error = ikeProcessEapMschapv2SuccessRequest(sa,
         (IkeEapMschapv2SuccessRequest *) request, length);
   }
   else if(request->opcode == IKE_EAP_MSCHAPV2_CODE_FAILURE)
   {
      //Process EAP MS-CHAP-V2 Failure Request packet
      error = ikeProcessEapMschapv2FailureRequest(sa,
         (IkeEapMschapv2FailureRequest *) request, length);
   }
   else
   {
      //Invalid opcode
      error = ERROR_INVALID_TYPE;
   }

   //Return status code
   return error;
}


/**
 * @brief Process EAP MS-CHAP-V2 Challenge packet
 * @param[in] sa Pointer to the IKE SA
 * @param[in] challenge Pointer to the EAP MS-CHAP-V2 Challenge packet
 * @param[in] length Length of the EAP MS-CHAP-V2 Challenge packet, in bytes
 * @return Error code
 **/

error_t ikeProcessEapMschapv2Challenge(IkeSaEntry *sa,
   const IkeEapMschapv2Challenge *challenge, size_t length)
{
   error_t error;
   IkeContext *context;

   //Point to the IKE context
   context = sa->context;

   //Check current state
   if(sa->eapState != IKE_EAP_STATE_INIT &&
      sa->eapState != IKE_EAP_STATE_IDENTITY)
   {
      return ERROR_WRONG_STATE;
   }

   //Malformed MS-CHAP-V2 packet?
   if(length < sizeof(IkeEapMschapv2Challenge))
      return ERROR_INVALID_LENGTH;

   //The MS-Length field is two octets and must be set to the value of the
   //Length field minus 5
   if(ntohs(challenge->msLength) != (length - sizeof(IkeEapRequest)))
      return ERROR_INVALID_LENGTH;

   //The Value-Size field is one octet and indicates the length of the
   //Challenge field. Since EAP MS-CHAP-V2 utilizes a 16 octet Challenge
   //field, it is set to 16
   if(challenge->valueSize != 16)
      return ERROR_INVALID_LENGTH;

   //The MS-CHAPv2-ID field is one octet and aids in matching MS-CHAP-V2
   //responses with requests
   sa->mschapv2Id = challenge->mschapv2Id;

   //The Challenge field is 16 octets
   osMemcpy(sa->authChallenge, challenge->challenge, 16);

   //The Peer-Challenge field is generated by the peer and is used in the
   //calculation of the NT-Response field
   error = context->prngAlgo->generate(context->prngContext, sa->peerChallenge,
      16);
   //Check status code
   if(error)
      return error;

   //The NT-Response field is an encoded function of the password, the user
   //name, the contents of the Peer-Challenge field and the received challenge
   //as output by the routine GenerateNTResponse()
   ikeEapMschapv2GenerateNtResponse(sa->authChallenge, sa->peerChallenge,
      context->username, context->password, sa->ntResponse);

   //Send an EAP MS-CHAP-V2 Response packet
   sa->eapState = IKE_EAP_STATE_MSCHAPV2_CHALLENGE;

   //Sucessful processing
   return NO_ERROR;
}


/**
 * @brief Process EAP MS-CHAP-V2 Success Request packet
 * @param[in] sa Pointer to the IKE SA
 * @param[in] request Pointer to the EAP MS-CHAP-V2 Success Request packet
 * @param[in] length Length of the EAP MS-CHAP-V2 Success Request packet, in bytes
 * @return Error code
 **/

error_t ikeProcessEapMschapv2SuccessRequest(IkeSaEntry *sa,
   const IkeEapMschapv2SuccessRequest *request, size_t length)
{
   bool_t valid;
   IkeContext *context;

   //Point to the IKE context
   context = sa->context;

   //Check current state
   if(sa->eapState != IKE_EAP_STATE_MSCHAPV2_CHALLENGE)
      return ERROR_WRONG_STATE;

   //Malformed MS-CHAP-V2 packet?
   if(length < sizeof(IkeEapMschapv2SuccessRequest))
      return ERROR_INVALID_LENGTH;

   //The MS-Length field is two octets and must be set to the value of the
   //Length field minus 5
   if(ntohs(request->msLength) != (length - sizeof(IkeEapRequest)))
      return ERROR_INVALID_LENGTH;

   //The Message field contains a 42-octet authenticator response string and a
   //printable message (refer to RFC 2759, section 5)
   if(length < (sizeof(IkeEapMschapv2SuccessRequest) + 42))
      return ERROR_INVALID_LENGTH;

   //The authenticating peer must verify the authenticator response when a
   //Success packet is received (refer to RFC 2759, section 5)
   valid = ikeEapMschapv2CheckAuthResponse(context->password, sa->ntResponse,
      sa->peerChallenge, sa->authChallenge, context->username,
      request->message);

   //Valid authenticator response?
   if(valid)
   {
      //Upon successful authentication, generate the master session key
      ikeEapMschapv2GenerateMasterSessionKey(context->password, sa->ntResponse,
         sa->msk);

      //An EAP method supporting key derivation must export a master session key
      //of at least 64 octet (refer to RFC 3748, section 7.10)
      sa->mskLen = 64;

      //If the peer successfully validates the EAP MS-CHAP-V2 Success Request
      //packet sent by the authenticator, then it must respond with an EAP
      //MS-CHAP-V2 Success Response packet
      sa->eapState = IKE_EAP_STATE_MSCHAPV2_SUCCESS;
   }
   else
   {
      //If the authenticator response is either missing or incorrect, the peer
      //must end the session (refer to RFC 2759, section 5)
      return ERROR_AUTHENTICATION_FAILED;
   }

   //Sucessful processing
   return NO_ERROR;
}


/**
 * @brief Process EAP MS-CHAP-V2 Failure Request packet
 * @param[in] sa Pointer to the IKE SA
 * @param[in] request Pointer to the EAP MS-CHAP-V2 Failure Request packet
 * @param[in] length Length of the EAP MS-CHAP-V2 Failure Request packet, in bytes
 * @return Error code
 **/

error_t ikeProcessEapMschapv2FailureRequest(IkeSaEntry *sa,
   const IkeEapMschapv2FailureRequest *request, size_t length)
{
   //Check current state
   if(sa->eapState != IKE_EAP_STATE_MSCHAPV2_CHALLENGE)
      return ERROR_WRONG_STATE;

   //Malformed MS-CHAP-V2 packet?
   if(length < sizeof(IkeEapMschapv2FailureRequest))
      return ERROR_INVALID_LENGTH;

   //The MS-Length field is two octets and must be set to the value of the
   //Length field minus 5
   if(ntohs(request->msLength) != (length - sizeof(IkeEapRequest)))
      return ERROR_INVALID_LENGTH;

   //Send an EAP MS-CHAP-V2 Failure Response packet
   sa->eapState = IKE_EAP_STATE_MSCHAPV2_FAILURE;

   //Sucessful processing
   return NO_ERROR;
}


/**
 * @brief Format EAP MS-CHAP-V2 Response packet
 * @param[in] sa Pointer to the IKE SA
 * @param[out] p Buffer where to format the EAP MS-CHAP-V2 packet
 * @param[out] written Length of the resulting EAP MS-CHAP-V2 packet
 * @return Error code
 **/

error_t ikeFormatEapMschapv2Response(IkeSaEntry *sa, uint8_t *p,
   size_t *written)
{
   size_t n;
   IkeContext *context;
   IkeEapMschapv2Response *response;

   //Point to the IKE context
   context = sa->context;

   //Point to the buffer where to format the EAP packet
   response = (IkeEapMschapv2Response *) p;

   //Format EAP header
   response->code = IKE_EAP_CODE_RESPONSE;
   response->identifier = sa->eapRequestId;
   response->type = IKE_EAP_METHOD_TYPE_MSCHAPV2;

   //The OpCode field is one octet and identifies the type of MS-CHAP-V2 packet
   response->opcode = IKE_EAP_MSCHAPV2_CODE_RESPONSE;

   //The MS-CHAPv2-ID field is one octet and aids in matching MS-CHAP-V2
   //responses with requests
   response->mschapv2Id = sa->mschapv2Id;

   //The Value-Size field is one octet and indicates the length of the Response
   //field. It is set to 49
   response->valueSize = 49;

   //The Peer-Challenge field is a 16-octet random number
   osMemcpy(response->peerChallenge, sa->peerChallenge, 16);

   //The Reserved field must be zero
   osMemset(response->reserved, 0, 8);

   //The NT-Response field is an encoded function of the password, the user
   //name, the contents of the Peer-Challenge field and the received
   //challenge as output by the routine GenerateNTResponse()
   osMemcpy(response->ntResponse, sa->ntResponse, 24);

   //The Flags field is reserved for future use and MUST be zero
   response->flags = 0;

   //Determine the length of the user name
   n = osStrlen(context->username);

   //The Name field is a string of 0 to (theoretically) 256 case-sensitive
   //ASCII characters which identifies the peer's user account name
   osMemcpy(response->name, context->username, n);

   //Length of the EAP MS-CHAP-V2 Response packet
   n += sizeof(IkeEapMschapv2Response);

   //The Length field is two octets and indicates the length of the EAP
   //packet including the Code, Identifier, Length, Type, OpCode,
   //MS-CHAPv2-ID, MS-Length, Value-Size, Challenge, and Name fields
   response->length = htons(n);

   //The MS-Length field is two octets and must be set to the value of the
   //Length field minus 5
   response->msLength = htons(n - sizeof(IkeEapResponse));

   //Total length of the EAP packet
   *written = n;

   //Sucessful processing
   return NO_ERROR;
}


